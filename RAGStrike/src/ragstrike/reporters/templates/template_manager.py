"""``TemplateManager`` and ``AssetManager`` -- reusable templates and inlined assets.

**Templates are formatted, never evaluated.** Substitution uses ``str.Template``, which understands
``$name`` and nothing else -- no expressions, no attribute traversal, no arbitrary code. A report
template is a file an operator edits, and a templating language that can execute would make styling
a report into a code-execution surface for a security tool.

That rules out Jinja here despite it being a dependency already: Jinja's power is exactly the
property this use does not want.

**Assets are inlined, not linked.** A report is emailed, attached to a ticket, and opened from a
downloads folder six months later. One that depends on a sibling CSS file is broken in all three
situations.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from string import Template
from typing import Any

