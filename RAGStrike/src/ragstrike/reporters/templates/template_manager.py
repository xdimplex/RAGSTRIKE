#: The shipped HTML shell. ``$body`` receives rendered sections; everything else is branding.
DEFAULT_HTML_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>$title</title>
<style>$css</style>
</head>
<body>
$body
<footer>$footer</footer>
</body>
</html>
"""


@dataclass(frozen=True, slots=True)
class TemplateSet:
    """The templates one render uses."""

    html: str = DEFAULT_HTML_TEMPLATE
    css: str = DEFAULT_CSS
    footer: str = "Generated by RAGStrike."
    extra: dict[str, str] = field(default_factory=dict)


class TemplateManager:
    """Loads templates from disk, falling back to the shipped ones.

    A missing template directory is normal, not an error -- the defaults are complete, and a report
    that refuses to render because nobody customized it would be useless out of the box.
    """

    def __init__(self, directory: Path | None = None) -> None:
        self.directory = directory

    def load(self) -> TemplateSet:
        if self.directory is None or not self.directory.is_dir():
            return TemplateSet()

        return TemplateSet(
            html=self._read("report.html", DEFAULT_HTML_TEMPLATE),
            css=self._read("report.css", DEFAULT_CSS),
            footer=self._read("footer.txt", "Generated by RAGStrike.").strip(),
        )

    def _read(self, name: str, fallback: str) -> str:
        if self.directory is None:
            return fallback
        path = self.directory / name
        try:
            return path.read_text(encoding="utf-8")
        except OSError:
            return fallback

    @staticmethod
    def apply(template: str, **values: Any) -> str:
        """Substitute ``$name`` placeholders.

        ``safe_substitute`` rather than ``substitute``: an operator's customized template with a
        stray ``$`` should render with that literal intact, not raise and lose the whole report.
        """
        return Template(template).safe_substitute(**values)


class AssetManager:
    """Supplies assets for embedding.

    Everything is inlined. See the module docstring: a report that depends on sibling files is
    broken the moment it is emailed, which is most of what happens to reports.
    """

    def __init__(self, directory: Path | None = None) -> None:
        self.directory = directory

    def css(self, override: str = "") -> str:
        if override:
            return override
        if self.directory:
            path = self.directory / "report.css"
            try:
                return path.read_text(encoding="utf-8")
            except OSError:
                pass
        return DEFAULT_CSS

    def logo(self, configured: str = "") -> str:
        """A logo placeholder.

        Returns whatever the configuration supplied -- a data URI, a caption, or nothing. The
        engine never fetches a remote image: a report that phones home when opened is a tracking
        pixel, whatever it was meant to be.
        """
        return configured


